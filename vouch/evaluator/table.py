"""The one results table. It is generated from the saved reports, never typed: the README shows it
between markers, and results/summary.json carries the same rows for the UI."""
from __future__ import annotations

import json
from pathlib import Path

from vouch.evaluator import run

README = run.ROOT / "README.md"
START = "<!-- results:start (generated by `python -m vouch.evaluator table` from results/*.json; do not edit) -->"
END = "<!-- results:end -->"
COLUMNS = ["Set", "Mode", "Model", "Date", "Runs", "Cost (USD)", "Caught", "False holds", "Evidence complete",
           "Money correct", "Never", "Demo (5 in a row)"]


def load(results_dir: Path = run.DEFAULT_RESULTS) -> list[dict]:
    return [json.loads(p.read_text(encoding="utf-8")) | {"report_file": p.name}
            for p in sorted(results_dir.glob("*.json")) if p.name != "summary.json"]


def latest(reports: list[dict]) -> list[dict]:
    """The newest report per set and mode. Scored reports count only if they rest on enough runs."""
    best: dict[tuple[str, str], dict] = {}
    for report in reports:
        if report["status"] == "scored" and report["runs"] < run.MIN_RUNS:
            continue
        key = (report["set"], report["mode"])
        if key not in best or report["scored_at"] > best[key]["scored_at"]:
            best[key] = report
    order = {name: i for i, name in enumerate(run.SETS)}
    return sorted(best.values(), key=lambda r: (r["mode"] != "model", order.get(r["set"], 99)))


def _measure(m: dict, planted: bool = True) -> str:
    if planted and m["total"] == 0:
        return "n/a"
    return f"{m['good']}/{m['total']}" + (f" ({m['percent']}%)" if m["percent"] is not None else "")


def row(report: dict) -> dict:
    base = {"Set": report["set"], "Mode": "live" if report["mode"] == "model" else "SCRIPTED",
            "Model": report["model"] or "-", "Date": report["date"], "Runs": str(report["runs"]),
            "Cost (USD)": report["cost_usd"], "report": report["report_file"]}
    if report["status"] != "scored":
        return {**base, **{c: "-" for c in COLUMNS[6:]}, "Caught": f"not scored: {report['reason']}"}
    m = report["metrics"]
    demo = report.get("demo", {})
    return {**base, "Caught": _measure(m["caught"]), "False holds": _measure(m["false_holds"], planted=False),
            "Evidence complete": _measure(m["evidence_complete"]),
            "Money correct": _measure(m["money_correct"]) + ("" if m["money_correct"]["books_balance"]
                                                            else ", books do not balance"),
            "Never": str(m["never"]["count"]),
            "Demo (5 in a row)": "-" if report["set"] != "main" else "not checked" if report["runs"] < run.DEMO_RUNS
            else "passed" if demo.get("passed") else f"not passed ({demo.get('longest_in_a_row', 0)} in a row)"}


def render(reports: list[dict]) -> str:
    rows = [row(r) for r in latest(reports)]
    lines = ["| " + " | ".join(COLUMNS) + " |", "|" + "|".join(" --- " for _ in COLUMNS) + "|"]
    lines += ["| " + " | ".join(r[c] for c in COLUMNS) + " |" for r in rows]
    if not any(r["Mode"] == "live" for r in rows):
        lines.append("")
        lines.append("No live-model report yet: the scores above come from the SCRIPTED playbook, not the model. "
                     "Run `python -m vouch score` with `ANTHROPIC_API_KEY` set to score the model.")
    lines.append("")
    lines.append("Targets: caught 100%, false holds under 5%, evidence complete 100%, money correct 100%, never 0. "
                 "Reports: " + ", ".join(f"`results/{r['report']}`" for r in rows) + ".")
    return "\n".join(lines)


def update(results_dir: Path = run.DEFAULT_RESULTS, readme: Path = README) -> str:
    """Write the table into the README between its markers, and the rows into results/summary.json."""
    reports = load(results_dir)
    table = render(reports)
    text = readme.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise ValueError(f"{readme.name} has no results markers")
    head, rest = text.split(START, 1)
    readme.write_text(f"{head}{START}\n{table}\n{END}{rest.split(END, 1)[1]}", encoding="utf-8")
    (results_dir / "summary.json").write_text(json.dumps({"rows": [row(r) for r in latest(reports)]}, indent=2,
                                                         ensure_ascii=False) + "\n", encoding="utf-8")
    return table


def shown(readme: Path = README) -> str:
    """The table as the README currently shows it."""
    text = readme.read_text(encoding="utf-8")
    return text.split(START, 1)[1].split(END, 1)[0].strip("\n")
